package com.jackwallner.headachelogger.ui

import android.graphics.Canvas
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import com.jackwallner.headachelogger.model.HeadacheEvent
import com.jackwallner.headachelogger.model.HeadacheSeverity
import com.jackwallner.headachelogger.model.HeatmapData
import com.jackwallner.headachelogger.model.HeatmapDay
import com.jackwallner.headachelogger.model.InsightsEngine
import com.jackwallner.headachelogger.model.InsightSummary
import java.io.File
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId
import java.time.format.DateTimeFormatter
import java.time.format.TextStyle
import java.util.Locale

/** Port of `ExportService.exportDoctorPDF`: a one-page US Letter report on the trailing 90 days. */
object ReportPdf {
    private const val WIDTH = 612
    private const val HEIGHT = 792
    private const val MARGIN = 36f
    private const val WINDOW_DAYS = 90
    private const val BRAND = 0xFFF2405C.toInt()
    private const val INK = 0xFF000000.toInt()
    private const val SECONDARY = 0x993C3C43.toInt()
    private const val TERTIARY = 0x4D3C3C43.toInt()
    private const val SEPARATOR = 0x4A3C3C43.toInt()

    private fun paint(size: Float, color: Int = INK, weight: Int = Typeface.NORMAL) = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
        this.color = color
        textSize = size
        typeface = Typeface.create(Typeface.DEFAULT, weight)
    }

    private fun medium(date: LocalDate) = DateTimeFormatter.ofPattern("MMM d, yyyy", Locale.getDefault()).format(date)

    fun render(events: List<HeadacheEvent>, dir: File, now: Instant = Instant.now(), zone: ZoneId = ZoneId.systemDefault()): File {
        dir.mkdirs()
        val today = now.atZone(zone).toLocalDate()
        val windowStart = today.minusDays((WINDOW_DAYS - 1).toLong())
        val startInstant = windowStart.atStartOfDay(zone).toInstant()
        val inWindow = events.filter { !it.timestamp.isBefore(startInstant) && !it.timestamp.isAfter(now) }
        val heatmap = HeatmapData.build(events, WINDOW_DAYS, now, zone)
        val summary = InsightsEngine.summarize(events)

        val file = File(dir, "headache-report-${now.epochSecond}.pdf")
        val doc = PdfDocument()
        val page = doc.startPage(PdfDocument.PageInfo.Builder(WIDTH, HEIGHT, 1).create())
        val c = page.canvas
        val width = WIDTH - MARGIN * 2
        var y = MARGIN
        y = header(c, y, width, windowStart, today) + 16
        y = summaryStats(c, y, width, inWindow, zone) + 18
        y = heatmapBlock(c, y, heatmap, zone) + 18
        topPatterns(c, y, width, summary)
        c.drawText(
            "Generated by One Tap Headache Tracker. Descriptive only, not a clinical diagnosis. Discuss with a qualified clinician.",
            MARGIN, HEIGHT - 40f + 8f, paint(8f, TERTIARY),
        )
        doc.finishPage(page)
        file.outputStream().use { doc.writeTo(it) }
        doc.close()
        return file
    }

    private fun header(c: Canvas, y: Float, width: Float, start: LocalDate, end: LocalDate): Float {
        val title = paint(26f, INK, Typeface.BOLD)
        c.drawText("Headache Report", MARGIN, y + 26f, title)
        val sub = paint(12f, SECONDARY)
        c.drawText("${medium(start)} to ${medium(end)}", MARGIN, y + 32f + 12f, sub)
        val generated = "Generated ${medium(end)}"
        c.drawText(generated, MARGIN + width - sub.measureText(generated), y + 32f + 12f, sub)
        val sepY = y + 54f
        c.drawLine(MARGIN, sepY, MARGIN + width, sepY, Paint().apply { color = SEPARATOR; strokeWidth = 0.5f })
        return sepY + 8f
    }

    private fun summaryStats(c: Canvas, y: Float, width: Float, events: List<HeadacheEvent>, zone: ZoneId): Float {
        val attackDays = events.map { it.timestamp.atZone(zone).toLocalDate() }.toSet().size
        val severe = events.count { it.severity == HeadacheSeverity.EXTREME }
        val topWeekday = events.groupingBy { it.weekdayIndex }.eachCount().maxByOrNull { it.value }?.key?.let { index ->
            java.time.DayOfWeek.of(if (index == 1) 7 else index - 1).getDisplayName(TextStyle.FULL, Locale.getDefault())
        } ?: "–"
        val topPart = events.groupingBy { it.partOfDay }.eachCount().maxByOrNull { it.value }?.key?.title ?: "–"
        val stats = listOf(
            "Attacks" to events.size.toString(),
            "Days affected" to attackDays.toString(),
            "Severe rated" to severe.toString(),
            "Peak weekday" to topWeekday,
            "Peak time" to topPart,
        )
        c.drawText("Summary", MARGIN, y + 14f, paint(14f, INK, Typeface.BOLD))
        val rowY = y + 24f
        val cell = width / stats.size
        val label = paint(9f, SECONDARY, Typeface.BOLD)
        val value = paint(20f, INK, Typeface.BOLD)
        stats.forEachIndexed { i, (name, v) ->
            val x = MARGIN + cell * i
            c.drawText(name.uppercase(), x, rowY + 9f, label)
            c.drawText(v, x, rowY + 12f + 20f, value)
        }
        return rowY + 40f
    }

    private fun cellColor(day: HeatmapDay): Int {
        if (day.count == 0) return 0x403C3C43
        val alpha = when (day.peakSeverity) {
            HeadacheSeverity.SLIGHT -> 0.35f
            HeadacheSeverity.MEDIUM -> 0.65f
            HeadacheSeverity.EXTREME -> 0.95f
            null -> if (day.count >= 2) 0.75f else 0.50f
        }
        return ((alpha * 255).toInt() shl 24) or (BRAND and 0x00FFFFFF)
    }

    private fun heatmapBlock(c: Canvas, y: Float, days: List<HeatmapDay>, zone: ZoneId): Float {
        c.drawText("Last 90 days", MARGIN, y + 14f, paint(14f, INK, Typeface.BOLD))
        val top = y + 22f
        val size = 14f
        val gap = 3f
        val first = days.firstOrNull() ?: return top + size
        var row = first.date.dayOfWeek.value % 7
        var column = 0
        val fill = Paint(Paint.ANTI_ALIAS_FLAG)
        days.forEach { day ->
            val x = MARGIN + column * (size + gap)
            val cy = top + row * (size + gap)
            fill.color = cellColor(day)
            c.drawRoundRect(RectF(x, cy, x + size, cy + size), 2.5f, 2.5f, fill)
            row += 1
            if (row >= 7) { row = 0; column += 1 }
        }
        val legendY = top + 7 * (size + gap) + 6f
        val legend = paint(9f, SECONDARY)
        c.drawText("Less", MARGIN, legendY + 10f, legend)
        var x = MARGIN + 32f
        listOf(
            HeatmapDay(LocalDate.now(zone), 0, null),
            HeatmapDay(LocalDate.now(zone), 1, HeadacheSeverity.SLIGHT),
            HeatmapDay(LocalDate.now(zone), 1, HeadacheSeverity.MEDIUM),
            HeatmapDay(LocalDate.now(zone), 1, HeadacheSeverity.EXTREME),
        ).forEach {
            fill.color = cellColor(it)
            c.drawRoundRect(RectF(x, legendY, x + 12f, legendY + 12f), 2f, 2f, fill)
            x += 16f
        }
        c.drawText("More", x, legendY + 10f, legend)
        return legendY + 18f
    }

    private fun topPatterns(c: Canvas, y: Float, width: Float, summary: InsightSummary) {
        c.drawText("Top patterns", MARGIN, y + 14f, paint(14f, INK, Typeface.BOLD))
        var cursor = y + 22f
        val title = paint(12f, INK, Typeface.BOLD)
        val detail = paint(10f, SECONDARY)
        val top = summary.insights.take(3)
        if (top.isEmpty()) {
            val body = if (summary.totalEvents < InsightsEngine.MINIMUM_SAMPLE_SIZE) {
                "Not enough logged headaches yet for pattern detection (need at least ${InsightsEngine.MINIMUM_SAMPLE_SIZE})."
            } else {
                "No single signal yet stands out at the confidence threshold. Continued logging will surface patterns as they emerge."
            }
            wrapped(c, body, cursor, width, detail)
            return
        }
        top.forEach { insight ->
            c.drawText(insight.title, MARGIN, cursor + 12f, title)
            cursor += 16f
            cursor = wrapped(c, insight.detail, cursor, width, detail) + 8f
        }
    }

    private fun wrapped(c: Canvas, text: String, y: Float, width: Float, paint: TextPaint): Float {
        val layout = StaticLayout.Builder.obtain(text, 0, text.length, paint, width.toInt()).setAlignment(Layout.Alignment.ALIGN_NORMAL).build()
        c.save()
        c.translate(MARGIN, y)
        layout.draw(c)
        c.restore()
        return y + layout.height
    }
}
